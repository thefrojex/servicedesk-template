CREATE OR REPLACE FUNCTION __APP_SCHEMA__.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = __APP_SCHEMA__, pg_temp AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

